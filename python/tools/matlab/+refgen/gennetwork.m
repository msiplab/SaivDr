function s = gennetwork(c)
%GENNETWORK Generate the reference data of a network test case
%
%   The layer graph is built by saivdr.dcnn.fcn_creatensoltlgraph2d (2-D) or
%   refgen.creatensoltlgraph3d (3-D), the regression layers are removed, and
%   all the angles are set at random. Gradients are computed by dlgradient
%   of sum_k <Z_k, dLdZ_k> with respect to the inputs and the learnables.
args = namedargs2cell(c.params);
if c.ndims == 2
    lgraph = saivdr.dcnn.fcn_creatensoltlgraph2d([],'InputSize',c.inputSize,args{:});
else
    lgraph = refgen.creatensoltlgraph3d([],'InputSize',c.inputSize,args{:});
end
isOutput = arrayfun(@(l) isa(l,'nnet.cnn.layer.RegressionOutputLayer'),lgraph.Layers);
if any(isOutput)
    lgraph = lgraph.removeLayers({lgraph.Layers(isOutput).Name});
end
if isfield(c,'serialize') && c.serialize
    error('Serialization is generated by gennetworkserialized')
end
dlnet = dlnetwork(lgraph);
L = dlnet.Learnables;
for iRow = 1:height(L)
    v = L.Value{iRow};
    L.Value{iRow} = dlarray(pi*(2*rand(size(v))-1));
end
dlnet.Learnables = L;
s = refgen.evalnetwork(dlnet,c);
end
